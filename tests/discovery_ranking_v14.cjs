const assert=require('node:assert/strict');
const R=require('../site/discovery-core.js');
const prefs={topics:[],degree:'any',modes:{research:'hard',qualification:'soft',email:'soft',opportunity:'soft',eligibility:'soft'}};
const row=(id,p={},score=1,unknown=2)=>({p:{page:id,...p},result:{score,unknown}});
const rows=Array.from({length:60},(_,i)=>row('s'+(i%3)+'-cs-'+i,{research_direction_raw:'图学习',email:'p@example.edu',title:'教授',supervisor:'博导'}));
const order=(items,seed='fixed',p=prefs,extra={})=>R.rankCandidates(items,p,extra,seed).rows.map(r=>r.p.page);
assert.deepEqual(order(rows),order([...rows].reverse()),'seeded ordering independent of source order');
assert.notDeepEqual(order(rows),order(rows,'other'),'different sessions mix equal-quality candidates');
assert.equal(new Set(order(rows)).size,rows.length);
const mixed=[row('empty',{email:'p@example.edu'}),row('bio'),row('raw',{research_direction_raw:'图学习'}),row('full',{research_direction_raw:'图学习',email:'p@example.edu',title:'教授',supervisor:'博导'})];
const qualityOrder=R.rankCandidates(mixed,prefs,{bio:{bio_excerpt:'视觉计算'}},'fixed').rows;
assert.equal(qualityOrder[0].p.page,'full');
assert.ok(qualityOrder.every((r,i)=>!i||qualityOrder[i-1].completeness[0]>=r.completeness[0]));
const unknown=R.completeness({title:'职称未知',supervisor:'导师资格未知'});
assert.deepEqual(unknown,[0]);
const explicit={...prefs,topics:['图学习']};
assert.deepEqual(order([row('full',{research_direction_raw:'图学习',email:'p@edu'},1,2),row('hit',{},2,1)],'fixed',explicit),['hit','full']);
const review=[row('generic',{},1),{...row('reviewed',{},2),result:{score:2,unknown:0,review:{}}}];
assert.equal(order(review)[0],'reviewed');
assert.equal(R.rankCandidates(rows,prefs,{},'fixed').matched,false);
assert.equal(R.rankCandidates(rows,explicit,{},'fixed').matched,true);
console.log('discovery ranking: 9 scenarios passed');
