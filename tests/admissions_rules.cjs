const assert=require('node:assert/strict'),rules=require('../site/admissions-core.js');
const school={id:'school',school:'test',dept:'',level:'school',year:2027,degree:'master',route:'exam',reviewed_at:'2026-10-14',review_hashes:{s:'old'}};
const dept={...school,id:'dept',dept:'cs',level:'program',program:'电子信息'};
const prefs={school:'test',dept:'cs',year:2027,degree:'master',route:'exam'};
assert.deepEqual(rules.select([school,dept],prefs).map(p=>p.id),['school','dept']);
assert.deepEqual(rules.select([school,dept],{...prefs,dept:'ai'}).map(p=>p.id),['school']);
assert.equal(rules.select([school,dept],{...prefs,year:2028}).length,0);
assert.equal(rules.select([school,dept],{...prefs,route:'recommend'}).length,0);
assert.equal(rules.select([school,dept],{...prefs,school:'other'}).length,0);
assert.equal(rules.select([{...dept,track:'special'}],{...prefs,track:'ordinary'}).length,0);
assert.equal(rules.select([school,{...dept,track:'special'}],{...prefs,track:'special'}).length,2);
assert.equal(rules.eventState({at:'2026-09-12T09:00:00+08:00',kind:'deadline'},'2026-10-14T00:00:00Z'),'past');
assert.equal(rules.eventState({at:'2026-09-04',kind:'exam'},'2026-09-04T10:00:00Z'),'future');
assert.equal(rules.eventState({at:'2026-09-04',kind:'exam'},'2026-09-05T00:00:00Z'),'past');
let observations={s:{status:'ok',hash:'old',last_success:'2026-10-14'}};
assert.equal(rules.quality(school,observations,'2026-10-14').state,'checked');
assert.equal(rules.quality(school,{s:{...observations.s,hash:'new'}},'2026-10-14').state,'changed');
assert.equal(rules.quality(school,{s:{...observations.s,status:'error'}},'2026-10-14').state,'error');
assert.equal(rules.quality(school,{},'2026-10-14').state,'unknown');
assert.equal(rules.quality(school,{s:{...observations.s,status:'fake'}},'2026-10-14').state,'unknown');
assert.equal(rules.quality(school,observations,'2026-10-23').state,'stale');
assert.equal(rules.quality({...school,reviewed_at:'2026-08-01'},observations,'2026-10-14').state,'review');
assert.equal(rules.quality({...school,reviewed_at:'2026-11-01'},observations,'2026-10-14').state,'review');
